def generate_draft(request: DraftRequest) -> DraftResponse:
    """
    Generate an academic draft section.

    All drafts are grounded in the provided papers with proper citations.
    A disclosure disclaimer is always included.
    """
    generators = {
        "literature_review": _generate_literature_review,
        "introduction": _generate_introduction,
        "methodology": _generate_methodology,
        "abstract": _generate_abstract,
        "conclusion": _generate_conclusion,
        "summary": _generate_summary,
    }

    gen_func = generators.get(request.section_type)
    if not gen_func:
        return DraftResponse(
            section_type=request.section_type,
            topic=request.topic,
            content=f"Error: Unknown section type '{request.section_type}'. "
                    f"Supported types: {', '.join(generators.keys())}",
            citations=[],
            word_count=0,
            disclaimer=DISCLAIMER,
        )

    content = gen_func(request.topic, request.papers, request.extracted_data,
                       request.max_words)
    citations = _build_citation_list(request.papers)
    word_count = len(content.split())

    return DraftResponse(
        section_type=request.section_type,
        topic=request.topic,
        content=content,
        citations=citations,
        word_count=word_count,
        disclaimer=DISCLAIMER,
    )
