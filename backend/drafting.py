def _format_authors(authors: list, max_authors: int = 3) -> str:
    """Format author names for citations (APA-style)."""
    if not authors:
        return "Unknown"
    names = [a.name if isinstance(a, dict) else a.name for a in authors[:max_authors]]
    if len(authors) > max_authors:
        return f"{names[0]} et al."
    if len(names) == 1:
        return names[0]
    return ", ".join(names[:-1]) + " & " + names[-1]


def _build_citation_list(papers: list[Paper]) -> list[dict]:
    """Build numbered citation list from papers."""
    citations = []
    for i, p in enumerate(papers, 1):
        citations.append({
            "ref_number": i,
            "authors": _format_authors(p.authors),
            "year": p.year or "n.d.",
            "title": p.title,
            "journal": p.journal or "N/A",
            "doi": p.doi or "",
            "quartile": p.quartile or "N/A",
        })
    return citations


def _in_text_citation(paper: Paper, ref_num: int) -> str:
    """Generate an in-text citation like (Smith et al., 2020) [1]."""
    author = _format_authors(paper.authors, max_authors=2)
    year = paper.year or "n.d."
    return f"({author}, {year}) [{ref_num}]"


