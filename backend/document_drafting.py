def generate_roadmap(document_type: str, format: str, topic: str, field: str = "") -> dict:
    """Generate a full document roadmap for the specified type and format."""
    gen_func = ROADMAP_GENERATORS.get(document_type)
    if not gen_func:
        return {
            "error": f"Unknown document type: {document_type}. Available: {list(ROADMAP_GENERATORS.keys())}"
        }

    sections, fmt_desc = gen_func(topic, format, field)

    # Calculate total estimated words
    total_words = sum(s["est_words"] for s in sections)

    # Build roadmap markdown
    md_lines = [f"# Document Roadmap: {topic}", ""]
    md_lines.append(f"**Document Type:** {DOCUMENT_TYPES[document_type]['label']}")
    md_lines.append(f"**Format:** {format}")
    md_lines.append(f"**Field:** {field or 'Not specified'}")
    md_lines.append(f"**Estimated Total Words:** {total_words:,}")
    md_lines.append(f"**Number of Sections:** {len(sections)}")
    md_lines.append("")
    md_lines.append(f"**Format Description:** {fmt_desc}")
    md_lines.append("")
    md_lines.append("---")
    md_lines.append("")

    for i, section in enumerate(sections, 1):
        md_lines.append(f"## {section['title']}")
        md_lines.append(f"**Purpose:** {section['purpose']}")
        md_lines.append(f"**Estimated Words:** {section['est_words']:,}")
        md_lines.append(f"**Writing Guidelines:** {section['guidelines']}")
        md_lines.append("")

    md_lines.append("---")
    md_lines.append("")
    md_lines.append(f"*{DISCLAIMER}*")

    return {
        "document_type": document_type,
        "document_type_label": DOCUMENT_TYPES[document_type]["label"],
        "format": format,
        "format_description": fmt_desc,
        "topic": topic,
        "field": field,
        "sections": sections,
        "total_estimated_words": total_words,
        "total_sections": len(sections),
        "roadmap_markdown": "\n".join(md_lines),
        "disclaimer": DISCLAIMER,
    }


