def suggest_research_topics(field: str, keywords: str = "", focus_novelty: bool = True, max_topics: int = 10) -> dict:
    """Generate research topic suggestions with novelty analysis."""
    field_key = field.lower().replace(" ", "_")
    field_data = RESEARCH_FIELDS.get(field_key, RESEARCH_FIELDS["interdisciplinary"])

    # Base topics from the field's trending gaps
    topics = list(field_data["trending_gaps"])

    # If keywords provided, generate topic variations
    if keywords:
        kw_list = [k.strip() for k in keywords.split(",") if k.strip()]
        for kw in kw_list[:3]:
            for sub_area in field_data["sub_areas"][:4]:
                topics.append(f"The role of {kw} in {sub_area.lower()} within {field_data['label'].lower()}")

    # Add sub-area-based topics
    for sub in field_data["sub_areas"]:
        topics.append(f"Unexplored determinants of outcomes in {sub.lower()}: evidence from developing contexts")

    # Deduplicate and limit
    seen = set()
    unique_topics = []
    for t in topics:
        key = t.lower()[:60]
        if key not in seen:
            seen.add(key)
            unique_topics.append(t)

    # Build structured suggestions with novelty analysis
    suggestions = []
    for i, topic in enumerate(unique_topics[:max_topics]):
        # Determine novelty factors
        novelty_factors = []
        if "Africa" in topic or "African" in topic or "ECOWAS" in topic or "Sahel" in topic or "Mano River" in topic:
            novelty_factors.append("Geographic focus on under-researched African context")
        if "AI" in topic or "digital" in topic.lower() or "blockchain" in topic.lower() or "cryptocurrency" in topic.lower():
            novelty_factors.append("Addresses emerging technology with limited empirical evidence")
        if "post-COVID" in topic or "post-pandemic" in topic:
            novelty_factors.append("Novel post-pandemic empirical context")
        if "climate" in topic.lower():
            novelty_factors.append("Climate-related research gap with policy urgency")
        if "informal" in topic.lower():
            novelty_factors.append("Focus on informal sector, often overlooked in mainstream research")
        if not novelty_factors:
            novelty_factors.append("Under-explored intersection with limited existing literature")

        # Suggest methodology
        methodologies = []
        if "effectiveness" in topic.lower() or "impact" in topic.lower():
            methodologies.append("Difference-in-Differences or IV/2SLS for causal identification")
        if "adoption" in topic.lower() or "barriers" in topic.lower():
            methodologies.append("Mixed methods: survey + econometric analysis")
        if "dynamics" in topic.lower() or "patterns" in topic.lower():
            methodologies.append("Panel data with fixed effects")
        if "relationship" in topic.lower() or "role" in topic.lower():
            methodologies.append("OLS/Panel regression with robustness checks")
        if not methodologies:
            methodologies.append("Quantitative analysis with panel/cross-sectional data")

        suggestions.append({
            "topic": topic,
            "field": field_data["label"],
            "sub_area": field_data["sub_areas"][i % len(field_data["sub_areas"])],
            "novelty_factors": novelty_factors,
            "suggested_methodology": methodologies,
            "research_gap": f"This topic addresses a gap in {field_data['label'].lower()} where {' '.join(novelty_factors[:2])}.",
            "estimated_difficulty": "High" if "AI" in topic or "blockchain" in topic.lower() else "Medium",
            "potential_journals": _suggest_journals(field_key, topic),
        })

    return {
        "field": field_data["label"],
        "sub_areas": field_data["sub_areas"],
        "topics": suggestions,
        "total": len(suggestions),
        "note": "Topics are generated based on current research gaps and trending issues. Verify novelty through literature search before proceeding." if focus_novelty else "Topics span major and minor issues in the field.",
    }


